CREATE TABLE src
(
    x UInt8
)
ENGINE = Null();

CREATE TABLE dst
(
    x UInt8
)
ENGINE = Memory();

CREATE MATERIALIZED VIEW mv_00508
TO dst
AS
SELECT *
FROM src;

INSERT INTO src;

SELECT *
FROM mv_00508
ORDER BY x ASC;

-- Detach MV and see if the data is still readable
DETACH TABLE mv_00508;

SELECT *
FROM dst
ORDER BY x ASC;

USE default;

-- Reattach MV (shortcut)
ATTACH TABLE CLICKHOUSE_DATABASE.mv_00508;

INSERT INTO CLICKHOUSE_DATABASE.src;

SELECT *
FROM CLICKHOUSE_DATABASE.mv_00508
ORDER BY x ASC;

-- Drop the MV and see if the data is still readable
DROP TABLE CLICKHOUSE_DATABASE.mv_00508;

SELECT *
FROM CLICKHOUSE_DATABASE.dst
ORDER BY x ASC;

